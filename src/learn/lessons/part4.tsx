/** A tiny two-hand example: "R:C4 D4 E4 | L:C3:4" style lists of [hand, beat, dur, codes]. */
function Hands({ notes, bars = 1, labels }: { notes: [HandEvent['hand'], number, number, string][]; bars?: number; labels?: boolean }) {
  const events: HandEvent[] = notes.map(([hand, beat, dur, codes]) => {
    const list = codes ? codes.split(' ') : [];
    return { hand, beat, dur, codes: list, midis: list.map((c) => midiOf(c)) };
  });
  return (
    <div style={{ width: '100%', maxWidth: 120 + bars * 230, margin: '0 auto' }}>
      <GrandStaff events={events} bars={bars} theme="light" labels={labels} />
    </div>
  );
}

/** A melody on the staff with real rhythm (light theme for the lesson paper). */
function Melody({ text, meter = 4, width = 40, chords }: { text: string; meter?: 3 | 4; width?: number; chords?: string[] }) {
  const notes = parseMelodyText(text);
  const items = staffItems(notes, meter);
  let bar = -1;
  return (
    <div style={{ width: '100%', maxWidth: items.length * width + 80, margin: '0 auto' }}>
      <StaffLine
        notes={items.map((it, i) => {
          if (it.barBefore || i === 0) bar += 1;
          return { code: it.code, dur: it.dur, rest: it.rest, barBefore: it.barBefore, above: (it.barBefore || i === 0) && chords ? chords[bar] : undefined };
        })}
        clef="treble"
        theme="light"
        noteWidth={width}
      />
    </div>
  );
}

